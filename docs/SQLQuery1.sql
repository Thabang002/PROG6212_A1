SELECT COURSE_DESCRIPTION AS COURSE_NAME
FROM SHORT_COURSE
LEFT JOIN COURSE_REGISTRATION ON SHORT_COURSE.COURSE_ID = COURSE_REGISTRATION.COURSE_ID
WHERE COURSE_REGISTRATION.COURSE_ID IS NULL;

SELECT 
    SC.COURSE_DESCRIPTION AS COURSE_NAME,
    SUM(CR.SPACES_AVAILABLE) AS "TOTAL SPACES"
FROM SHORT_COURSE SC
LEFT JOIN COURSE_REGISTRATION CR ON SC.COURSE_ID = CR.COURSE_ID
GROUP BY SC.COURSE_ID, SC.COURSE_DESCRIPTION
ORDER BY SC.COURSE_DESCRIPTION ASC;

SELECT TOP 1
    SC.COURSE_DESCRIPTION AS COURSE_NAME,
    C.CAMPUS_NAME,
    CR.SPACES_AVAILABLE
FROM COURSE_REGISTRATION CR
JOIN SHORT_COURSE SC ON CR.COURSE_ID = SC.COURSE_ID
JOIN CAMPUS C ON CR.CAMPUS_ID = C.CAMPUS_ID
WHERE CR.COURSE_ID = 'STA301'
ORDER BY CR.SPACES_AVAILABLE DESC;