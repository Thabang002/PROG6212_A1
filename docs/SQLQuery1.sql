-- Create the database
CREATE DATABASE COURSES;
USE COURSES;

-- Create SHORT_COURSE table
CREATE TABLE SHORT_COURSE (
    COURSE_ID VARCHAR(10) PRIMARY KEY,
    COURSE_DESCRIPTION VARCHAR(100) NOT NULL,
    COURSE_PRICE DECIMAL(10,2) NOT NULL
);

-- Create CAMPUS table
CREATE TABLE CAMPUS (
    CAMPUS_ID VARCHAR(10) PRIMARY KEY,
    CAMPUS_NAME VARCHAR(50) NOT NULL,
    CAMPUS_ADDRESS VARCHAR(100) NOT NULL
);

-- Create COURSE_REGISTRATION table (composite primary key)
CREATE TABLE COURSE_REGISTRATION (
    COURSE_ID VARCHAR(10),
    CAMPUS_ID VARCHAR(10),
    SPACES_AVAILABLE INT,
    PRIMARY KEY (COURSE_ID, CAMPUS_ID),
    FOREIGN KEY (COURSE_ID) REFERENCES SHORT_COURSE(COURSE_ID),
    FOREIGN KEY (CAMPUS_ID) REFERENCES CAMPUS(CAMPUS_ID)
);

